#!/usr/bin/env python3
"""Generate a professional word-level tracked changes PDF.

Compares the original LaTeX manuscript from Google Drive against the revised
LaTeX manuscript generated by pandoc, and compiles a redline tracked changes PDF
where all additions and deletions are highlighted in red.
"""

from __future__ import annotations

import difflib
import logging
import re
import shutil
import subprocess
import sys
from pathlib import Path

logging.basicConfig(level=logging.INFO, format="%(levelname)s: %(message)s")
logger = logging.getLogger(__name__)

def escape_latex(text: str) -> str:
    """Escape LaTeX special characters in raw text."""
    # Only escape if not already inside a LaTeX command
    return text.replace("&", r"\&").replace("%", r"\%").replace("_", r"\_").replace("#", r"\#")

def latex_token_diff(old_text: str, new_text: str) -> str:
    """Perform a LaTeX-safe word-level diff on paragraphs."""
    # Tokenizer that splits LaTeX commands, math, plain words, and punctuation
    pat = re.compile(r"\\[a-zA-Z]+(?:\{[^{}]*\})*|\$.*?\$|[\w\x27-]+|[^\w\s\\]+")
    old_toks = pat.findall(old_text)
    new_toks = pat.findall(new_text)
    
    sm = difflib.SequenceMatcher(None, old_toks, new_toks)
    result = []
    
    for op, i1, i2, j1, j2 in sm.get_opcodes():
        if op == "equal":
            result.extend(old_toks[i1:i2])
        elif op == "replace":
            old_part = old_toks[i1:i2]
            new_part = new_toks[j1:j2]
            # Wrap deletions in \deleted{...} (ignoring LaTeX structural tags)
            for tok in old_part:
                if tok.startswith("\\") or tok.startswith("$"):
                    continue
                result.append(f"\\deleted{{{escape_latex(tok)}}}")
            # Wrap additions in \added{...} (preserving LaTeX structural tags)
            for tok in new_part:
                if tok.startswith("\\") or tok.startswith("$"):
                    result.append(tok)
                else:
                    result.append(f"\\added{{{escape_latex(tok)}}}")
        elif op == "delete":
            for tok in old_toks[i1:i2]:
                if tok.startswith("\\") or tok.startswith("$"):
                    continue
                result.append(f"\\deleted{{{escape_latex(tok)}}}")
        elif op == "insert":
            for tok in new_toks[j1:j2]:
                if tok.startswith("\\") or tok.startswith("$"):
                    result.append(tok)
                else:
                    result.append(f"\\added{{{escape_latex(tok)}}}")
                    
    # Reconstruct paragraph text with proper spacing
    res_str = ""
    for i, tok in enumerate(result):
        if i > 0 and not re.match(r"^[^\w\s\\]", tok):
            res_str += " "
        res_str += tok
    return res_str

def main() -> int:
    repo_root = Path(__file__).resolve().parents[1]
    
    orig_path = repo_root / "original" / "Journal_paper" / "final_sample.tex"
    rev_path = repo_root / "revised" / "revised_paper.tex"
    out_path = repo_root / "revised" / "tracked_changes.tex"
    
    if not orig_path.exists():
        logger.error("Original LaTeX file not found: %s", orig_path)
        return 1
    if not rev_path.exists():
        logger.error("Revised LaTeX file not found: %s", rev_path)
        return 1
        
    logger.info("Reading original LaTeX: %s", orig_path)
    orig_lines = orig_path.read_text().splitlines()
    
    logger.info("Reading revised LaTeX: %s", rev_path)
    rev_lines = rev_path.read_text().splitlines()
    
    preamble_lines = []
    body_lines = []
    in_body = False
    
    for line in orig_lines:
        if "\\begin{document}" in line:
            preamble_lines.append(line)
            in_body = True
            continue
        if not in_body:
            preamble_lines.append(line)
        else:
            body_lines.append(line)
            
    tracked_packages = [
        "\\usepackage{xcolor}",
        "\\usepackage[normalem]{ulem}",
        "\\definecolor{trackred}{RGB}{200,0,0}",
        "\\newcommand{\\added}[1]{{\\color{trackred}#1}}",
        "\\newcommand{\\deleted}[1]{{\\color{trackred}\\sout{#1}}}",
        "\\providecommand{\\tightlist}{\\setlength{\\itemsep}{0pt}\\setlength{\\parskip}{0pt}}",
    ]
    
    doc_index = -1
    for idx, line in enumerate(preamble_lines):
        if "\\begin{document}" in line:
            doc_index = idx
            break
            
    if doc_index != -1:
        preamble_lines = preamble_lines[:doc_index] + tracked_packages + preamble_lines[doc_index:]
    else:
        preamble_lines.extend(tracked_packages)
        preamble_lines.append("\\begin{document}")
        
    orig_body = "\n".join(body_lines)
    rev_body_lines = rev_lines
                
    orig_paragraphs = re.split(r'\n\s*\n', orig_body)
    rev_paragraphs = re.split(r'\n\s*\n', "\n".join(rev_body_lines))
        
    logger.info("Comparing %d original vs %d revised paragraphs...", len(orig_paragraphs), len(rev_paragraphs))
    
    with open(out_path, "w") as f:
        # Write preamble
        f.write("\n".join(preamble_lines) + "\n")
        
        # Match paragraphs
        sm = difflib.SequenceMatcher(None, orig_paragraphs, rev_paragraphs)
        
        for op, i1, i2, j1, j2 in sm.get_opcodes():
            if op == 'equal':
                for p in orig_paragraphs[i1:i2]:
                    f.write(p + "\n\n")
            elif op == 'replace':
                old_p = " ".join(orig_paragraphs[i1:i2])
                new_p = " ".join(rev_paragraphs[j1:j2])
                # If paragraph contains structural environments (e.g. tables, abstract block, authors), output as-is
                if "begin{" in old_p or "begin{" in new_p or "item" in old_p or "item" in new_p:
                    f.write(new_p + "\n\n")
                else:
                    diff_p = latex_token_diff(old_p, new_p)
                    f.write(diff_p + "\n\n")
            elif op == 'delete':
                for p in orig_paragraphs[i1:i2]:
                    if "begin{" in p or "item" in p:
                        continue
                    p_esc = escape_latex(p)
                    f.write(f"\\deleted{{{p_esc}}}\n\n")
            elif op == 'insert':
                for p in rev_paragraphs[j1:j2]:
                    if "begin{" in p or "item" in p:
                        f.write(p + "\n\n")
                    else:
                        p_esc = escape_latex(p)
                        f.write(f"\\added{{{p_esc}}}\n\n")
                        
        f.write("\\end{document}\n")
        
    logger.info("Generated %s successfully!", out_path)
    return 0

if __name__ == "__main__":
    sys.exit(main())